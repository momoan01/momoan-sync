export function settingsTranslator(language?: string): SettingsTranslator {
	const locale = resolveSettingsLanguage(language);
	return (text, values = {}) => {
		let message = locale === "en" ? text : translations[text]?.[locale === "ko" ? 0 : locale === "ja" ? 1 : 2] ?? text;
		for (const [key, value] of Object.entries(values)) message = message.replaceAll("{" + key + "}", String(value));
		return message;
	};
}
