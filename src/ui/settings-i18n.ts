export function resolveSettingsLanguage(language?: string): SettingsLanguage {
	const value = language && language !== "auto" ? language :
		(typeof navigator === "undefined" ? "en" : navigator.language);
	const prefix = value?.toLowerCase().split(/[-_]/)[0];
	return prefix === "ko" || prefix === "ja" || prefix === "zh" ? prefix : "en";
}

